function sortFa(a: string, b: string) {
  return a.localeCompare(b, "fa");
}

export const IRAN_PROVINCES: IranProvince[] = RAW.map((p) => ({
  name: p.name,
  cities: [...p.cities].sort(sortFa),
})).sort((a, b) => sortFa(a.name, b.name));

export const IRAN_PROVINCE_OPTIONS = IRAN_PROVINCES.map((p) => ({
  value: p.name,
  label: p.name,
}));

export function citiesOfProvince(province: string) {
  const found = IRAN_PROVINCES.find((p) => p.name === province);
  return (found?.cities ?? []).map((c) => ({ value: c, label: c }));
}
